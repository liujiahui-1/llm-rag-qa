print("""普通请求（/api/ask）：
    前端发问 -> 服务器憋 5 秒 -> 一次性蹦出整段答案
    用户盯着空屏幕 5 秒，会以为卡死了

流式（/api/ask/stream）：
    前端发问 -> 服务器每生成一个字就立刻往外推一个字
    用户看到文字一个个蹦出来，感觉"它在想"

技术上，服务器往外推的每一小块，格式长这样（SSE = Server-Sent Events）：

    data: {"delta": "国家"}\\n\\n
    data: {"delta": "奖学金"}\\n\\n
    data: {"delta": "为八千元"}\\n\\n
    data: [DONE]\\n\\n

规则只有三条：
    · 每行以 data: 开头
    · 行尾必须是两个换行 \\n\\n（这是"一条消息到此结束"的分隔符，少一个浏览器就不认）
    · 最后发一条 data: [DONE] 告诉前端"没了"

app.py 里 sse() 函数就是在拼这个格式，stream_model() 在解析 DeepSeek 回来的流。
下面手动模拟一遍这个格式：""")

for piece in ["国家", "奖学金", "为八千元", "，", "按学年发放"]:
    print(f"    data: {json.dumps({'delta': piece}, ensure_ascii=False)}")
    print()                      # 这个真实空行 = 那个 \n\n，代表一条消息结束
    time.sleep(0.15)
print("    data: [DONE]")
print()

print("""
左边这一列就是浏览器网络面板里真实看到的东西。
所以"流式输出"这个词一点都不神秘：就是服务器不憋着，生成一点发一点，
前端收到一点就往外 append 一点。

⚠️ 面试如果追问"SSE 和 WebSocket 区别"（可能问，不用慌）：
    SSE 是单向（服务器 -> 浏览器），基于普通 HTTP，实现简单，适合"只推文字"
    WebSocket 是双向，要专门协议，适合聊天室那种双方都要说话的场景
    我这个场景只需要服务器往外推字，所以 SSE 足够，没必要上 WebSocket。
""")


